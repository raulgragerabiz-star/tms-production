#    /seguimiento: se introduce el Nº de pedido + el codigo postal de la
#    entrega (mismo criterio que cualquier transportista de mercado) y se
#    ve solo el estado de ese pedido, nada mas. El Portal Cliente con
#    usuario/contrasena que ya existia se queda tal cual, sin tocar, para
#    quien lo tuviera configurado -- esto es una via adicional, no un
#    reemplazo. La carga de pedidos por Excel ya no crea usuarios de
#    Portal Cliente al dar de alta un cliente nuevo.
#
# Sin cambios de base de datos ni dependencias nuevas. Ejecutar desde la
