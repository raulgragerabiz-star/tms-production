# reales de Raul:
#
# 1) LA IMPORTACION YA NO SE HACE EN UNA SOLA PETICION HTTP LARGA. Con un
#    archivo grande (miles de pedidos), el POST /orders/import se quedaba
#    varios minutos esperando a que terminara todo el lote, y la conexion
#    se cortaba con un error de red antes de recibir respuesta. Ahora el
#    POST responde al instante con un identificador de trabajo, el backend
