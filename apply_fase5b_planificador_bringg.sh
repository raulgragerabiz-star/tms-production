#     ruta (no hay todavia un horario de salida configurable por almacen).
#     Si a la ruta le falta alguna coordenada (almacen o algun punto de
#     entrega sin lat/lng), sencillamente no se calcula -- no rompe nada de
#     lo que ya funcionaba, esas paradas simplemente no aparecen con hora en
#     la tabla ni en el Gantt (se ordenan al final / no se dibujan).
#  3) Nuevo endpoint de solo lectura 'GET /routes/dispatch-board' -- a
#     diferencia de '/routes/planner-board' (solo rutas draft/optimized,
#     pensado para el tablero de arrastrar y soltar), este trae TODAS las
#     rutas del almacen/fecha dados sin importar su estado, con su envio y
#     ultima posicion GPS si ya esta en curso. No sustituye ni modifica
#     ningun endpoint existente.
#
# Sin cambios de esquema de base de datos (RouteStop.eta ya existia,
